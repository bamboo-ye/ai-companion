export function searchGuideTopics<T extends string>(topics: readonly GuideTopic<T>[], query: string): readonly GuideTopic<T>[] {
  const terms = query.trim().toLocaleLowerCase().split(/\s+/).filter(Boolean);
  if (!terms.length) return topics;
  return topics.filter((topic) => {
    const content = [topic.group, topic.title, topic.summary, topic.path, ...topic.steps, topic.tip, topic.example ?? ""].join(" ").toLocaleLowerCase();
    return terms.every((term) => content.includes(term));
  });
}
